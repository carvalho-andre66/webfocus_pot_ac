SUMMARY = """
-DEFAULTH &REGION_FILTER = FOC_NONE;
-DEFAULT &MIN_AMOUNT = 100;
-SET &BRAND = 'Demo Co';
-SET &WINDOW = &YYMD;
SET ASNAMES = ON
SET HOLDLIST = PRINTONLY
DEFINE FILE SALES_FACT
NET_AMOUNT/D12.2 = GROSS_AMOUNT - DISCOUNT_AMOUNT;
REGION_LABEL/A40 = 'Region ' | REGION_NAME;
HEADING_TEXT/A30 = '&BRAND';
ODD_FIELD/A10 = MYSTERYFN(REGION_NAME, 'A10');
END
JOIN STORE_ID IN SALES_FACT TO STORE_ID IN STORE_DIM AS J1
TABLE FILE SALES_FACT
SUM NET_AMOUNT
    GROSS_AMOUNT NOPRINT
    STORE_NAME
BY REGION_LABEL
BY STORE_ID
WHERE GROSS_AMOUNT GT &MIN_AMOUNT;
WHERE REGION_NAME EQ '&REGION_FILTER';
WHERE STATUS_CODE EQ 'A';
ON TABLE HOLD AS STEP_ONE FORMAT FOCUS
END
TABLE FILE STEP_ONE
SUM NET_AMOUNT AS 'Net Sales'
    MAX.NET_AMOUNT AS 'Largest'
COMPUTE NET_SHARE/D6.2% = NET_AMOUNT / GROSS_AMOUNT * 100;
COMPUTE BEST_SHARE/D6.2% = MAX.NET_SHARE;
BY REGION_LABEL AS 'Region'
BY HIGHEST 5 NET_AMOUNT NOPRINT
WHERE TOTAL NET_AMOUNT GT 0;
WHERE STORE_ID NE &WINDOW;
ON TABLE PCHOLD FORMAT HTML
END
"""

